import { test, expect } from "@playwright/test";

test("owner confirms additions, role changes and removals; uncertain saves require refresh", async ({page}) => {
  await page.route("**/rest/v1/rpc/race_invitations",r=>r.fulfill({json:[]}));
  await page.route("**/rest/v1/rpc/my_race_invitations",r=>r.fulfill({json:[]}));
  await page.addInitScript(() => localStorage.setItem("tent-flow-dev-auth",JSON.stringify({access_token:"token",refresh_token:"refresh",token_type:"bearer",expires_at:Math.floor(Date.now()/1000)+3600,user:{id:"owner"}})));
  await page.route("**/rest/v1/rpc/my_races",r=>r.fulfill({json:[{id:"race",name:"Team Test",role:"owner",state:"active"}]}));
  await page.route("**/rest/v1/rpc/patient_board",r=>r.fulfill({json:{pods:[],visits:[],placements:[],turnovers:[]}}));
  let members=[{id:"owner",email:"owner@example.com",role:"owner"},{id:"member",email:"member@example.com",role:"viewer"}];
  await page.route("**/rest/v1/rpc/race_team",r=>r.fulfill({json:members}));
  const writes: any[]=[];
  let fail=false;
  await page.route("**/rest/v1/rpc/set_race_member",async r=>{
    const body=r.request().postDataJSON(); writes.push(body);
    if(fail) return r.fulfill({status:409,json:{message:"Stale"}});
    members=members.filter(m=>m.email!==body.p_email);
    if(body.p_role) members.push({id:body.p_email,email:body.p_email,role:body.p_role});
    await r.fulfill({status:204});
  });
  await page.goto("/");
  await page.getByRole("button",{name:"Open board"}).click();
  await page.getByText("Menu",{exact:true}).click();
  await page.getByRole("button",{name:"Manage Team",exact:true}).click();
  const dialog=page.getByRole("dialog");
  await expect(dialog.getByText("owner@example.com",{exact:true})).toBeVisible();
  await expect(dialog.getByLabel("Role for owner@example.com")).toHaveCount(0);
  await dialog.getByLabel("Role for member@example.com").selectOption("editor");
  expect(writes).toHaveLength(0);
  await dialog.getByRole("button",{name:"Back",exact:true}).click();
  expect(writes).toHaveLength(0);
  await dialog.getByLabel("Role for member@example.com").selectOption("editor");
  await dialog.getByRole("button",{name:"Confirm change"}).click();
  await expect(dialog.getByLabel("Role for member@example.com")).toHaveValue("editor");
  expect(writes[0]).toMatchObject({p_race:"race",p_expected_role:"viewer",p_role:"editor"});
  await dialog.getByRole("button",{name:"Remove member@example.com",exact:true}).click();
  await dialog.getByRole("button",{name:"Confirm change"}).click();
  await expect(dialog.getByText("member@example.com",{exact:true})).toHaveCount(0);
  await dialog.getByLabel("Existing account email").fill("new@example.com");
  await dialog.getByRole("button",{name:"Add member",exact:true}).click();
  await dialog.getByRole("button",{name:"Confirm change"}).click();
  await expect(dialog.getByLabel("Role for new@example.com")).toHaveValue("viewer");
  await page.setViewportSize({width:375,height:812});
  await page.screenshot({path:"test-results/manage-team-phone.png",fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  fail=true;
  await dialog.getByLabel("Role for new@example.com").selectOption("editor");
  await dialog.getByRole("button",{name:"Confirm change"}).click();
  await expect(dialog.getByRole("alert")).toContainText("Change not confirmed");
  await expect(dialog.getByRole("button",{name:"Confirm change"})).toBeDisabled();
  await dialog.getByRole("button",{name:"Refresh team"}).click();
  await expect(dialog.getByLabel("Role for new@example.com")).toHaveValue("viewer");
});
